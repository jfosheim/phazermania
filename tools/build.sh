#!/bin/sh
# Builds both deliverables from one source: tools/app-body.html + data/*
#
#   index.html        local build. Loads data via <script src>, which works over
#                     file:// where fetch() does not. Includes diagrams.js and
#                     richs.js, so the parts index links to the offline images.
#
#   dist/index.html   the same page as a full HTML document, for GitHub Pages.
#
#   phazermania.html  self-contained build for publishing as an Artifact.
#                     Data is inlined. Diagrams are deliberately EXCLUDED: they are
#                     watermarked Yamaha illustrations, and 22 MB would blow the
#                     16 MB artifact cap anyway. The published page links to
#                     Partzilla instead.
#
# data/specs.json is the ONLY copy of the spec data. data/specs.js is generated
# here (a one-line wrapper) so index.html can load it over file://. Never edit
# specs.js by hand.
#
# The build stops if tools/check.js finds a data error. Warnings are printed
# but do not stop it.
set -e
cd "$(dirname "$0")/.."

# ---- 1. specs.js from specs.json --------------------------------------------
{
  echo '/* GENERATED by tools/build.sh from data/specs.json - do not edit. */'
  printf 'window.SPECS = '
  cat data/specs.json
  echo ';'
} > data/specs.js

# ---- 2. Rich's fiche manifest ------------------------------------------------
# Regenerate from the harvest TSV, so the two never drift. Grouped as
# "<year>/<slug>" -> { section: uuid }; the image is data/diagrams-richs/<uuid>.gif.
# Only runs when the images are on disk: the awk step drops rows whose image is
# missing, so running it without the images would empty the manifest.
if [ -s data/richs-index.tsv ] && [ -d data/diagrams-richs ]; then
  tmp=$(mktemp)
  {
    echo '/* Rich'"'"'s Yamaha fiche manifest: "<year>/<slug>" -> { section: uuid }.'
    echo ' *'
    echo ' * Image path:  data/diagrams-richs/<uuid>.gif'
    echo ' * Source page: https://www.richsyamaha.com/Parts/Parts-Diagrams/yamaha/snowmobiles/<year>/<slug>/<section>/<uuid>'
    echo ' *'
    echo ' * Regenerate with tools/fetch-richs.sh, which harvests every section a'
    echo ' * model has - far more than the 16 our Partzilla scraper was told to keep.'
    echo ' *'
    echo ' * Watermarked Yamaha illustrations. Local shop reference only; the'
    echo ' * published artifact deliberately excludes them.'
    echo ' */'
    # A handful of sections are listed on the site but have no image on the CDN.
    # Drop them here so the app never renders a dead link.
    awk -F'\t' -v dir=data/diagrams-richs '
      { f = dir "/" $3 ".gif"
        if ((getline line < f) < 0) next          # unreadable => no image
        close(f)
        if ($1 != prev) { if (prev != "") printf "},\n"; printf "\"%s\":{", $1; prev = $1; first = 1 }
        if (!first) printf ","
        printf "\"%s\":\"%s\"", $2, $3; first = 0 }
      END { if (prev != "") printf "}" }
    ' data/richs-index.tsv | sed '1s/^/window.RICHS = {/'
    echo '};'
  } > "$tmp"
  mv "$tmp" data/richs.js
else
  echo "richs.js: images not on disk, keeping the existing manifest"
fi

# ---- 3. data checks ------------------------------------------------------------
node tools/check.js

# ---- 4. the two pages ----------------------------------------------------------
{
  echo '<!doctype html>'
  echo '<html lang="en">'
  echo '<head>'
  echo '<meta charset="utf-8">'
  echo '<meta name="viewport" content="width=device-width,initial-scale=1">'
  echo '<script src="data/specs.js"></script>'
  echo '<script src="data/parts.js"></script>'
  echo '<script src="data/diagrams.js"></script>'
  [ -s data/richs.js ] && echo '<script src="data/richs.js"></script>'
  echo '</head>'
  echo '<body>'
  cat tools/app-body.html
  echo '</body>'
  echo '</html>'
} > index.html

{
  echo '<script>'; cat data/specs.js; echo '</script>'
  echo '<script>'; cat data/parts.js; echo '</script>'
  cat tools/app-body.html
} > phazermania.html

# ---- 5. the website (GitHub Pages) ------------------------------------------
# Same content as phazermania.html, wrapped in a full document: the Artifact
# host adds the doctype and viewport itself, a plain web server does not.
mkdir -p dist
{
  echo '<!doctype html>'
  echo '<html lang="en">'
  echo '<head>'
  echo '<meta charset="utf-8">'
  echo '<meta name="viewport" content="width=device-width,initial-scale=1">'
  echo '<meta name="description" content="Specs, parts and tuning reference for 1986-1995 Yamaha Phazer, Phazer II and Venture snowmobiles.">'
  echo '</head>'
  echo '<body>'
  cat phazermania.html
  echo '</body>'
  echo '</html>'
} > dist/index.html

echo "index.html       $(wc -c < index.html) bytes  (+ $(ls data/diagrams 2>/dev/null | wc -l) partzilla, $(ls data/diagrams-richs 2>/dev/null | wc -l) richs diagrams)"
echo "phazermania.html $(wc -c < phazermania.html) bytes"
echo "dist/index.html  $(wc -c < dist/index.html) bytes"
